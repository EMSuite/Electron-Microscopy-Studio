//
//  AgentDoorCoverage.swift
//  Role: What the agent door covers (#558, as mac4DSTEM#223 did for mac4DSTEM): every control a person can use in macEM, by its
//        accessibility identifier, with how an agent reaches it. A tool does it, the agent already sees it (`get_window`, the
//        pictures, `get_results`), it is left to the person on purpose (with the reason), or it is a gap with its open issue.
//        `AgentDoorCoverageTests` reads the app's sources and fails when a control has no row here, a row names a tool the door does not
//        have, or a row outlives its control, so a new control cannot ship undecided.
//
//        The EDS room's own controls are MacEMUI's and are reached through its shared tools (`get_eds`, `set_eds`, `run_eds`,
//        `EDXAgentTools`); the room itself is `workspace.\(room.id)` (select_room). Identifiers built at run time are listed as written
//        in the source ("workspace.\(room.id)").
//

